const strings = { en, pt_BR: ptBR, pt: ptBR, es };

export const useMessagesTranslation = () => {
  const { language } = useLocalization();
  return useMemo(() => {
    const data = { ...en, ...strings[language] };
    return (key, values) => {
      const text = data[key] ?? key;
      if (!values) {
        return text;
      }
      return Object.entries(values).reduce(
        (result, [name, value]) => result.replace(`{${name}}`, value),
        text,
      );
    };
  }, [language]);
};
